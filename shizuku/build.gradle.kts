// rish_shizuku.dex: the dex of :shizuku-shell (R8, ShizukuShellLoader only), delivered as a generated assets folder
// ---------------------------------------------------------------------------------------------------------------------------------------------------------------------
abstract class ShizukuRishDexTask : DefaultTask() {
    // the unsigned release APK of :shizuku-shell (the .apk file in outputs/apk/release)
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val shellApk: ConfigurableFileCollection

    // becomes an assets folder: rish_shizuku.dex (the name ShellTutorialActivity looks for, DEX_NAME)
    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun extract() {
        val apks = shellApk.files.filter { it.isFile && it.extension == "apk" }
        if (apks.size != 1) {
            throw GradleException(
                "Shizuku: expected exactly one release APK of :shizuku-shell in outputs/apk/release/, found ${apks.size} ($apks). " +
                    "The APK is only a container for classes.dex (rish_shizuku.dex): look at the build output of :shizuku-shell."
            )
        }
        val out = outputDir.get().asFile
        out.deleteRecursively()
        out.mkdirs()
        ZipFile(apks.single()).use { zip ->
            val dexes = zip.entries().asSequence().filter { Regex("classes\\d*\\.dex").matches(it.name) }.toList()
            if (dexes.size != 1) {
                throw GradleException(
                    "Shizuku: ${apks.single().name} holds ${dexes.size} dex files (${dexes.map { it.name }}), expected exactly 1. " +
                        "rish_shizuku.dex is started by app_process as ONE file: the shell loader must stay small enough for one dex."
                )
            }
            zip.getInputStream(dexes.single()).use { input ->
                File(out, "rish_shizuku.dex").outputStream().use { input.copyTo(it) }
            }
        }
    }
}

val shizukuRishDex = tasks.register<ShizukuRishDexTask>("shizukuRishDex") {
    group = "shizuku"
    description = "Builds :shizuku-shell (release, R8) and exposes its classes.dex as assets/rish_shizuku.dex of this library"
    dependsOn(":shizuku-shell:assembleRelease")
    val shellApkDir = project(":shizuku-shell").layout.buildDirectory.dir("outputs/apk/release")
    shellApk.from(fileTree(shellApkDir) { include("*.apk") })
    outputDir.set(layout.buildDirectory.dir("generated/shizuku/rishDex/assets"))
}

androidComponents {
    onVariants { variant ->
        // generated assets folder: AGP makes the merge-assets tasks (and lint, package ...) depend on the task by itself
        variant.sources.assets?.addGeneratedSourceDirectory(shizukuRishDex, ShizukuRishDexTask::outputDir)
    }
}

