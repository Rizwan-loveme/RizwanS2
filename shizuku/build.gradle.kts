// :shizuku = upstream's `manager` project (Shizuku v13.6.0, Apache-2.0): the Shizuku manager app (start with Wireless debugging / root, authorised apps list, terminal tutorial,
// settings) as an Android LIBRARY, package moe.shizuku.manager (upstream package kept: the sources import its R / ViewBinding classes). Step 3E of the Shizuku plan, see shizuku/README.md
// and NOTICE-Shizuku.md. Only part of the build with -PincludeShizuku=true (settings.gradle.kts, step 3B); the Win11 :app depends on it from step 3F on.
//
// The source is NOT in the project zip: shizuku/tools/fetch-upstream.sh (task :shizuku:fetchShizukuUpstream) clones it into shizuku/upstream/ and shizuku/tools/patch-upstream.py
// (task :shizuku:patchShizukuUpstream) turns it into a library (host package, resource prefix sh_, library manifest, ShizukuLocales ...). This build file only points the source sets
// at that checkout, exactly like :mika. Every :shizuku-* module (modules/after-fetch.gradle.kts) and this one wait for the two tasks.
//
// What upstream's manager/build.gradle does and what is done here instead (the file was read in full in 3E, v13.6.0):
//   * com.android.application -> com.android.library: no applicationId, versionCode / versionName (upstream: from `git rev-list --count HEAD`, which is 1 in a shallow clone; the
//     patched code never reads them: the manager shows the host app's version), no signing config (signing.gradle is upstream's own key), no APK renaming / copying of mapping files,
//     no minify / shrinkResources (:app decides; consumer-rules.pro carries the keep rules), no `collapseReleaseResourceNames` (aapt2 post-processing of the APK, an app-only step)
//   * buildFeatures: viewBinding + prefab as upstream; buildConfig false (the patch script removed the two BuildConfig.APPLICATION_ID uses: a library has no BuildConfig constants)
//   * three Rikka plugins -> two: refine (rewrites calls to hidden Android APIs) and materialthemebuilder (Theme.Material3.Light|Dark.Shizuku, palette attributes, textColorOnXxx) are
//     applied; autoresconfig is NOT (it throws in a library): its output, rikka.shizuku.manager.ShizukuLocales, is generated by the patch script (3A)
//   * native: upstream's manager/src/main/jni/CMakeLists.txt, unchanged: libshizuku.so (an add_executable named like a library: the starter that the manager copies / runs, needs
//     libcxx only) and libadb.so (ADB pairing, BoringSSL + libcxx). -DANDROID_STL=none + the Prefab packages boringssl and cxx (below), as upstream. The project's NDK (ext.ndkVer) and
//     CMake 3.22.1 like :ppsspp and :shizuku-rish; ABIs: all four like upstream, -PshizukuAbis=arm64-v8a,... narrows them (same property as :shizuku-rish). libshizuku.so is started
//     from the app's native library dir, so it has to be EXTRACTED to disk: :app already sets packaging { jniLibs { useLegacyPackaging = true } } (a library cannot set it)
//   * rish_shizuku.dex: upstream's :shell module copies its dex into manager/src/main/assets (the source tree). Here the task shizukuRishDex runs :shizuku-shell:assembleRelease, takes the
//     one classes.dex out of the unsigned release APK and registers its output folder as a GENERATED assets folder of every variant (AGP Variant API), so nothing is written into
//     shizuku/upstream/ and the merge-assets tasks wait for it by themselves. Upstream's own assets/rish (the shell script that the terminal tutorial copies) is a normal assets folder
//   * minSdk 26 like every Win11 module (upstream 24), compileSdk 37 (upstream 36), Java 21 (same), Kotlin 2.2.10 (root build file; upstream 2.1.21)
//
// The Rikka AppCompat fork (decision 1 in shizuku/README.md): upstream depends on dev.rikka.rikkax.appcompat:appcompat, a modified copy of AndroidX AppCompat with the SAME class names, and
// removes androidx.appcompat from its build. Both in one APK = duplicate classes, and swapping the fork into the whole Win11 app would change AppCompat for every module. So the fork is
// excluded from every configuration of this module (it can still arrive through another rikkax library: :app excludes it too, step 3F) and the stock AndroidX AppCompat is used,
// 1.6.1 = the version the fork is based on and the lowest the project already asks for (:j2me 1.8.0 and :seal 1.7.0 win, one version per library). Not applied here: upstream's exclusion of
// androidx.profileinstaller (an app-only matter).
//
// Library versions (decision 3): upstream's, except androidx.lifecycle 2.9.0 -> 2.8.7 (what :seal asks for, so no new lift) and kotlinx-coroutines 1.10.2 -> 1.9.0 (the root build file pins
// every kotlinx-coroutines artifact to one version). All of them are only a floor: Gradle takes the highest version per library across the build.
